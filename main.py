a=float(input("enter your first number"))
b=float(input("enter your second number"))
op=input("enter your operation(+,-,*,/,%):")
if(op=="+"):
    print("sum:", a+b)
elif(op=="-"):
    print("difference:", a-b)
elif (op=="*"):
    print("multiplication:", a*b)
elif(op=="/"):
    print("division:", a/b)
elif(op=="%"):
    print("modulo:", a%b)
